  let currentLang = "en";

  function getLang() {
    return currentLang;
  }

  function setLang(langCode) {
    if (translations[langCode]) {
      currentLang = langCode;
      applyTranslations();
      return true;
    }
    return false;
  }

  function t(key) {
    if (translations[currentLang] && translations[currentLang][key]) {
      return translations[currentLang][key];
    }
    return (translations.en && translations.en[key]) || key;
  }

  function applyTranslations() {
    document.querySelectorAll("[data-i18n]").forEach(el => {
      const key = el.getAttribute("data-i18n");
      const val = t(key);
      if (val) {
        if (el.tagName === "INPUT" && el.getAttribute("type") === "text") {
          el.placeholder = val;
        } else {
          el.textContent = val;
        }
      }
    });

    const langBadge = document.getElementById("current-lang-label");
    if (langBadge) {
      const labels = {
        en: "English",
        hi: "हिंदी (Hindi)",
        mr: "मराठी (Marathi)",
        ta: "தமிழ் (Tamil)",
        te: "తెలుగు (Telugu)",
        bn: "বাংলা (Bengali)"
      };
      langBadge.textContent = labels[currentLang] || "English";
    }

    window.dispatchEvent(new CustomEvent("fasalmarg:langchange", { detail: { lang: currentLang } }));
  }

  return {
    getLang,
    setLang,
    t,
    applyTranslations,
    translations
  };
